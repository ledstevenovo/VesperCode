"""Relaxed v2 reference identities.

The v1 package uses content-addressed values as both references and security
bindings.  v2 deliberately separates those concerns: these values are opaque
correlation keys generated by the harness.  They identify rows and log events;
they do not authenticate file contents, policy state, or a request payload.

The v1 models remain available in their original modules for read-only legacy
inspection.  New v2 code must use these small standard-library value objects
instead of adding another digest-bound v1 model.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from uuid import uuid4


def new_id() -> str:
    """Return an opaque, non-content-derived UUID reference."""

    return str(uuid4())


def new_run_id() -> str:
    return new_id()


def new_candidate_id() -> str:
    return new_id()


def new_snapshot_id() -> str:
    return new_id()


def new_action_id() -> str:
    return new_id()


def new_approval_id() -> str:
    return new_id()


def new_disclosure_id() -> str:
    return new_id()


def new_artifact_id() -> str:
    return new_id()


def new_transaction_id() -> str:
    return new_id()


def new_diff_id() -> str:
    """A diff record's opaque reference (Route B / B1)."""

    return new_id()


def new_reference_profile_id() -> str:
    """A reference profile record's opaque reference (Route B / B1)."""

    return new_id()


def new_validation_run_id() -> str:
    """A validation run's opaque reference (Route B / B1)."""

    return new_id()


def new_grant_id() -> str:
    """A disclosure grant's opaque reference (Route B / B2)."""

    return new_id()


def new_authorization_id() -> str:
    """A per-request disclosure authorization's opaque reference (Route B / B2)."""

    return new_id()


def new_endpoint_id() -> str:
    """A provider endpoint's opaque reference (Route B / B2)."""

    return new_id()


def new_request_id() -> str:
    """A provider request's opaque reference (Route B / B2)."""

    return new_id()


def new_subject_id() -> str:
    return new_id()


def _identifier(value: str, field_name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{field_name} must be a non-empty string")
    if len(value.encode("utf-8")) > 256:
        raise ValueError(f"{field_name} is too long")
    return value


def _revision(value: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise ValueError("revision must be a non-negative integer")
    return value


def _timestamp(value: str) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError("expires_at must be a non-empty timestamp")
    try:
        datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError("expires_at must be an ISO-8601 timestamp") from exc
    return value


@dataclass(frozen=True, slots=True)
class CandidateIdentityV2:
    """A database reference to a candidate and its control-plane revision."""

    candidate_id: str
    snapshot_id: str
    revision: int

    def __post_init__(self) -> None:
        object.__setattr__(
            self, "candidate_id", _identifier(self.candidate_id, "candidate_id")
        )
        object.__setattr__(
            self, "snapshot_id", _identifier(self.snapshot_id, "snapshot_id")
        )
        object.__setattr__(self, "revision", _revision(self.revision))


@dataclass(frozen=True, slots=True)
class ActionInstanceV2:
    """A harness-generated action row reference and its fixed action family."""

    action_id: str
    action_type: str

    def __post_init__(self) -> None:
        object.__setattr__(self, "action_id", _identifier(self.action_id, "action_id"))
        object.__setattr__(
            self, "action_type", _identifier(self.action_type, "action_type")
        )


@dataclass(frozen=True, slots=True)
class FinalWritebackSubjectV2:
    """A short-lived writeback review reference.

    The subject points to a candidate row and an expiry.  It is not a claim
    that the candidate bytes are unchanged; the writeback service must query
    the current candidate revision before consuming an approval.
    """

    subject_id: str
    candidate_id: str
    expires_at: str

    def __post_init__(self) -> None:
        object.__setattr__(
            self, "subject_id", _identifier(self.subject_id, "subject_id")
        )
        object.__setattr__(
            self, "candidate_id", _identifier(self.candidate_id, "candidate_id")
        )
        object.__setattr__(self, "expires_at", _timestamp(self.expires_at))


