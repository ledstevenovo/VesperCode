@dataclass(frozen=True)
class PathGuard:
    """One handle-bound authorization guard over frozen facts only.

    ``git_facts`` carries the sealed Git/ignore observations (9.C),
    ``reference`` carries the frozen editable policy (6.A), and
    ``inspector`` is the 9.A object observation port (production binding:
    real Win32 handles).  Authorization facts and handles only: no
    workspace mutation, patch parsing, policy widening, or string-only
    authorization can exist here.
    """

    git_facts: SealedGitFactsV1
    reference: ReferenceProfileManifestV1
    inspector: ObjectInspectionPortV1 = field(
        default_factory=lambda: inspect_workspace_object
    )

    def __post_init__(self) -> None:
        if self.git_facts.ignore_rules_digest != ignore_rules_digest(
            self.git_facts.ignore_rules
        ):
            raise ValueError("sealed ignore facts do not match their digest")

    def authorize_existing(
        self,
        root: WorkspaceIdentityV1,
        path: CanonicalRelativePathV1,
        expected_kind: WorkspaceObjectKindV1,
    ) -> AuthorizedObjectHandleV1:
        """Authorize one existing object for REPLACE when all facts match.

        Order follows SPEC §4.3: Task 9.A object rejections (including
        aliases) propagate unchanged, then sensitive-path, protected-
        artifact, and editable-policy facts decide.  The returned sealed
        identity is re-verified against the root facts (volume, ancestry,
        kind, reparse, link, ADS, ACL) before it can authorize.
        """
        if _policy_binding_mismatch(self.git_facts, self.reference):
            return _rejected_object("TREE_INTEGRITY_FAILED")
        try:
            identity = self.inspector(root, path)
        except WorkspaceObjectRejectedV1 as error:
            return _rejected_object(error.error_code)
        fact_error = _verify_object_facts(identity, root, expected_kind)
        if fact_error is not None:
            return _rejected_object(fact_error)
        sensitive = sensitive_path_rule_id(path.value)
        if sensitive is not None:
            return _rejected_object("PATH_SENSITIVE")
        if protected_artifact_path(path.value):
            return _rejected_object("PROTECTED_ARTIFACT_CHANGED")
        if not self.reference.editable_path_policy.matches(path, "REPLACE"):
            return _rejected_object("PATCH_PATH_NOT_EDITABLE")
        return AuthorizedObjectHandleV1(
            schema_version=1, kind="AUTHORIZED", authorized_object=identity
        )

    def authorize_create(
        self, root: WorkspaceIdentityV1, path: CanonicalRelativePathV1
    ) -> AuthorizedParentHandleV1:
        """Authorize one CREATE parent when every fact family matches.

        An exact existing object rejects with ``PATH_EXISTS``; a case or
        Unicode alias of an existing object rejects with
        ``PATH_ALIAS_COLLISION`` (the Task 9.A observation port proves
        the alias from the final path); every ancestor must be a proven
        directory under the root; the new path must be non-sensitive,
        non-protected, editable, and non-ignored under the sealed ignore
        rules.
        """
        if _policy_binding_mismatch(self.git_facts, self.reference):
            return _rejected_parent("TREE_INTEGRITY_FAILED")
        try:
            self.inspector(root, path)
        except WorkspaceObjectRejectedV1 as error:
            if error.error_code != "WORKSPACE_OBJECT_NOT_FOUND":
                return _rejected_parent(error.error_code)
        else:
            return _rejected_parent("PATH_EXISTS")
        sensitive = sensitive_path_rule_id(path.value)
        if sensitive is not None:
            return _rejected_parent("PATH_SENSITIVE")
        if protected_artifact_path(path.value):
            return _rejected_parent("PROTECTED_ARTIFACT_CHANGED")
        if not self.reference.editable_path_policy.matches(path, "CREATE"):
            return _rejected_parent("PATCH_PATH_NOT_EDITABLE")
        if path_is_ignored(self.git_facts.ignore_rules, path.value):
            return _rejected_parent("PATH_IGNORED")
        parent, parent_error = self._prove_parent_chain(root, path)
        if parent_error is not None:
            return _rejected_parent(parent_error)
        if parent is None:
            # No provable parent.  With the frozen built-in editable
            # policy this branch is structurally unreachable — a CREATE
            # must start with ``src/`` and therefore has at least one
            # ancestor — but the closed rejection is the correct
            # fail-closed outcome for any future policy shape; it is
            # never an assertion.
            return _rejected_parent("PATH_PARENT_NOT_FOUND")
        return AuthorizedParentHandleV1(
            schema_version=1, kind="AUTHORIZED", authorized_parent=parent
        )

    def _prove_parent_chain(
        self, root: WorkspaceIdentityV1, path: CanonicalRelativePathV1
    ) -> tuple[FinalObjectIdentityV1 | None, PathAuthorizationErrorCodeV1 | None]:
        """Prove every ancestor directory under the root.

        Returns the deepest proven parent identity and None, or None and
        the stable closed error for the first unprovable link
        (``PATH_PARENT_NOT_FOUND`` for a missing ancestor,
        ``PATH_PARENT_NOT_DIRECTORY`` for a non-directory ancestor, or
        the propagated 9.A fact rejection).
        """
        segments = path.value.split("/")
        proven: FinalObjectIdentityV1 | None = None
        for count in range(1, len(segments)):
            parent_path = CanonicalRelativePathV1("/".join(segments[:count]))
            try:
                identity = self.inspector(root, parent_path)
            except WorkspaceObjectRejectedV1 as error:
                if error.error_code == "WORKSPACE_OBJECT_NOT_FOUND":
                    return None, "PATH_PARENT_NOT_FOUND"
                return None, error.error_code
            fact_error = _verify_object_facts(identity, root, "DIRECTORY")
            if fact_error is not None:
                if fact_error == "WORKSPACE_OBJECT_WRONG_KIND":
                    return None, "PATH_PARENT_NOT_DIRECTORY"
                return None, fact_error
            proven = identity
        return proven, None


def _rejected_object(
    error_code: PathAuthorizationErrorCodeV1,
) -> AuthorizedObjectHandleV1:
    return AuthorizedObjectHandleV1(
        schema_version=1, kind="REJECTED", error_code=error_code
    )


def _rejected_parent(
    error_code: PathAuthorizationErrorCodeV1,
) -> AuthorizedParentHandleV1:
    return AuthorizedParentHandleV1(
        schema_version=1, kind="REJECTED", error_code=error_code
    )


def _verify_object_facts(
    identity: FinalObjectIdentityV1,
    root: WorkspaceIdentityV1,
    expected_kind: WorkspaceObjectKindV1,
) -> PathAuthorizationErrorCodeV1 | None:
    """Re-verify the sealed object facts against the root; None when all
    facts match, else the stable closed error code."""
    if identity.volume_serial_number != root.volume_serial_number:
        return "WORKSPACE_OBJECT_VOLUME_MISMATCH"
    try:
        common = os.path.commonpath(
            [
                os.path.normcase(identity.final_absolute_path),
                os.path.normcase(root.canonical_absolute_path),
            ]
        )
    except ValueError:
        return "PATH_OUTSIDE_WORKSPACE"
    if common != os.path.normcase(root.canonical_absolute_path):
        return "PATH_OUTSIDE_WORKSPACE"
    if identity.object_kind != expected_kind:
        return "WORKSPACE_OBJECT_WRONG_KIND"
    if identity.reparse_tag != 0 or (
        identity.object_kind == "FILE" and identity.link_count != 1
    ):
        return "UNSUPPORTED_WORKSPACE_OBJECT"
    if identity.has_alternate_data_streams:
        return "UNSUPPORTED_WORKSPACE_OBJECT"
    if not identity.acl_observable:
        return "WORKSPACE_OBJECT_ACL_UNPROVEN"
    return None
