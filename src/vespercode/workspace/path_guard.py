"""T09.1 legacy step 9.D: handle-bound existing/create path authorization.

``PathGuard`` authorizes an existing object (REPLACE semantics) or a
CREATE parent only when every fact family matches: canonical lexical paths
(Task 4.D), handle-derived final-object/root facts (Task 9.A observation
port), sealed Git/ignore facts (Task 9.C), sensitive-path rules and
protected-artifact rules (SPEC §1.4.2–1.4.3), and the frozen
``EditablePathPolicyV1`` (Task 6.A).  Every failure returns a closed
REJECTED handle with a stable error code and never falls back to string
authorization, never mutates the workspace, and never widens editable
policy.

This module also owns the shared path-fact tables consumed by the Git
preflight (9.C): the sensitive-path rules, the protected-artifact rules,
and the sealed gitignore rule vocabulary — one frozen source for both
consumers, imported one-directionally by ``git_preflight``.
"""

